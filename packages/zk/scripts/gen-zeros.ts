// Writes contracts/src/privacy/PoseidonZeros.sol: the empty-subtree value at each level of a depth-20 Poseidon tree,
// zeros[0] = 0, zeros[i] = Poseidon(zeros[i-1], zeros[i-1]) (circomlib parameters, the same as src/index.ts).
//   bun scripts/gen-zeros.ts
import { writeFileSync } from "node:fs";
import { zeroValues, TREE_DEPTH } from "../src/index.ts";
const ROOT = new URL("../../../", import.meta.url).pathname;
const z = await zeroValues(TREE_DEPTH);
const cases = z.map((v, i) => `        if (level == ${i}) return ${v};`).join("\n");
writeFileSync(`${ROOT}contracts/src/privacy/PoseidonZeros.sol`, `// SPDX-License-Identifier: MIT
// GENERATED by packages/zk/scripts/gen-zeros.ts. Do not edit.
pragma solidity ^0.8.28;

/// @notice Empty-subtree roots of a depth-${TREE_DEPTH} Poseidon (circomlib, BN254) Merkle tree: zeros(0) = 0,
///         zeros(i) = Poseidon(zeros(i-1), zeros(i-1)). zeros(${TREE_DEPTH}) is the root of the empty tree.
library PoseidonZeros {
    uint256 internal constant DEPTH = ${TREE_DEPTH};

    function zeros(uint256 level) internal pure returns (uint256) {
${cases}
        revert("level");
    }
}
`);
console.log("wrote PoseidonZeros.sol, empty root", z[TREE_DEPTH]);
process.exit(0);
