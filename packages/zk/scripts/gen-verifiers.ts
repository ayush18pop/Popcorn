// Writes contracts/src/proofs/<Name>Verifier.sol for each circuit from setup/<circuit>_vkey.json: a Groth16 (BN254)
// verifier with the same layout as ExploitVerifier (one 4-pair ecPairing call, exact precompile stipends, inputs < r,
// never reverts on malformed input). Gas: about 181,000 pairing + 6,150 per public input + overhead.
//   bun scripts/gen-verifiers.ts [circuit ...]     (default: membership withdraw stealth)
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../../../", import.meta.url).pathname;
const ZK = new URL("../", import.meta.url).pathname;
const NAMES: Record<string, { contract: string; about: string; inputs: string }> = {
  membership: { contract: "MembershipVerifier", about: "private membership (circuits/membership.circom)", inputs: "[root, nullifierHash, signalHash, externalNullifier]" },
  withdraw: { contract: "WithdrawVerifier", about: "private pool withdrawal with an association set (circuits/withdraw.circom)", inputs: "[root, assocRoot, nullifierHash, recipient, fee, scope]" },
  stealth: { contract: "StealthVerifier", about: "spending a stealth payment (circuits/stealth.circom)", inputs: "[commitment, recipient, fee]" },
};

for (const circuit of process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(NAMES)) {
  const meta = NAMES[circuit];
  if (!meta) throw new Error(`unknown circuit ${circuit}`);
  const raw = readFileSync(`${ZK}setup/${circuit}_vkey.json`);
  const vk = JSON.parse(raw.toString());
  if (vk.protocol !== "groth16" || vk.curve !== "bn128") throw new Error("unexpected vk");
  const n: number = vk.nPublic;
  const c = (name: string, v: string) => `    uint256 internal constant ${name} = ${v};`;
  const g2 = (nm: string, p: string[][]) => [c(`${nm}_X1`, p[0][1]), c(`${nm}_X0`, p[0][0]), c(`${nm}_Y1`, p[1][1]), c(`${nm}_Y0`, p[1][0])];
  const consts = [
    c("ALPHA_X", vk.vk_alpha_1[0]), c("ALPHA_Y", vk.vk_alpha_1[1]),
    ...g2("BETA", vk.vk_beta_2), ...g2("GAMMA", vk.vk_gamma_2), ...g2("DELTA", vk.vk_delta_2),
    ...vk.IC.flatMap((p: string[], i: number) => [c(`IC${i}_X`, p[0]), c(`IC${i}_Y`, p[1])]),
  ];
  const acc = Array.from({ length: n }, (_, i) => `
            s := calldataload(add(x, ${32 * i}))
            ok := and(ok, lt(s, R))
            mstore(add(m, 448), IC${i + 1}_X)
            mstore(add(m, 480), IC${i + 1}_Y)
            mstore(add(m, 512), s)
            ok := and(ok, staticcall(6000, 7, add(m, 448), 96, add(m, 448), 64))
            ok := and(ok, staticcall(150, 6, add(m, 384), 128, add(m, 384), 64))`).join("\n");
  const sha = createHash("sha256").update(raw).digest("hex");
  const sol = `// SPDX-License-Identifier: MIT
// GENERATED by packages/zk/scripts/gen-verifiers.ts from packages/zk/setup/${circuit}_vkey.json (sha256 ${sha}). Do not edit.
pragma solidity ^0.8.24;

import {IVerifier} from "src/interfaces/IVerifier.sol";

/// @title ${meta.contract}
/// @notice Groth16 (BN254) verifier for ${meta.about}. Zero-knowledge, not post-quantum.
///         proof: 256 bytes (A.x, A.y, B.x.im, B.x.re, B.y.im, B.y.re, C.x, C.y). inputs (${n}): ${meta.inputs}.
///         Returns false (never reverts) on wrong lengths, out-of-range values, points not on the curve or a bad proof.
///         Precompile stipends are the EIP-1108 prices (ecMul 6,000, ecAdd 150, ecPairing 181,000 for 4 pairs), so the
///         caller must forward about ${181000 + 6150 * n + 8000} gas. Development trusted setup (packages/zk/scripts/setup.sh).
contract ${meta.contract} is IVerifier {
    uint256 internal constant R = 21888242871839275222246405745257275088548364400416034343698204186575808495617;
    uint256 internal constant Q = 21888242871839275222246405745257275088696311157297823662689037894645226208583;

${consts.join("\n")}

    function verify(bytes calldata proof, uint256[] calldata inputs) external view returns (bool ok) {
        if (proof.length != 256 || inputs.length != ${n}) return false;
        assembly ("memory-safe") {
            let m := mload(0x40)
            let p := proof.offset
            let x := inputs.offset
            ok := 1
            for { let i := 0 } lt(i, 256) { i := add(i, 32) } { ok := and(ok, lt(calldataload(add(p, i)), Q)) }

            mstore(add(m, 384), IC0_X)
            mstore(add(m, 416), IC0_Y)
            let s := 0
${acc}

            // e(-A, B) * e(alpha, beta) * e(vk_x, gamma) * e(C, delta) == 1
            mstore(m, calldataload(p))
            mstore(add(m, 32), mod(sub(Q, calldataload(add(p, 32))), Q))
            calldatacopy(add(m, 64), add(p, 64), 128)
            mstore(add(m, 192), ALPHA_X)
            mstore(add(m, 224), ALPHA_Y)
            mstore(add(m, 256), BETA_X1)
            mstore(add(m, 288), BETA_X0)
            mstore(add(m, 320), BETA_Y1)
            mstore(add(m, 352), BETA_Y0)
            mstore(add(m, 448), GAMMA_X1)
            mstore(add(m, 480), GAMMA_X0)
            mstore(add(m, 512), GAMMA_Y1)
            mstore(add(m, 544), GAMMA_Y0)
            calldatacopy(add(m, 576), add(p, 192), 64)
            mstore(add(m, 640), DELTA_X1)
            mstore(add(m, 672), DELTA_X0)
            mstore(add(m, 704), DELTA_Y1)
            mstore(add(m, 736), DELTA_Y0)
            ok := and(ok, staticcall(181000, 8, m, 768, m, 32))
            ok := and(ok, mload(m))
        }
    }
}
`;
  writeFileSync(`${ROOT}contracts/src/proofs/${meta.contract}.sol`, sol);
  console.log(`wrote contracts/src/proofs/${meta.contract}.sol (${n} public inputs)`);
}
