// Generates src/artifacts/ruleset.generated.ts (abi + creation bytecode of RuleSetLogic, RuleSetPublisher, RuleSetContract) from
// `forge build`, so the SDK (and a UI) can deploy rule-set rule contracts without compiling Solidity.
//   bun scripts/gen-ruleset-artifact.ts     (run `forge build` in contracts/ first)
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../../../", import.meta.url).pathname;
const OUT = new URL("../src/artifacts/ruleset.generated.ts", import.meta.url).pathname;
const art = (n: string) => {
  const j = JSON.parse(readFileSync(`${ROOT}contracts/out/${n}.sol/${n}.json`, "utf8")) as { abi: unknown[]; bytecode: { object: string } };
  const bytecode = j.bytecode.object.startsWith("0x") ? j.bytecode.object : `0x${j.bytecode.object}`;
  return { abi: j.abi, bytecode };
};
const logic = art("RuleSetLogic");
const publisher = art("RuleSetPublisher");
const ruleContract = art("RuleSetContract");
const src = `// GENERATED by scripts/gen-ruleset-artifact.ts from contracts/out (solc 0.8.33, bytecode_hash none). Do not edit.
import type { Hex } from "viem";

/** Shared data-driven logic. constructor(address publisher, uint256 stakeAmount). */
export const ruleSetLogicAbi = ${JSON.stringify(logic.abi, null, 2)} as const;
export const ruleSetLogicBytecode: Hex = "${logic.bytecode}";

/** Validates configs and stores each as a data contract at a CREATE2 address. No constructor arguments. */
export const ruleSetPublisherAbi = ${JSON.stringify(publisher.abi, null, 2)} as const;
export const ruleSetPublisherBytecode: Hex = "${publisher.bytecode}";

/** Per-config logic (config validated in the constructor, one logic per config). constructor(bytes config, uint256 stakeAmount). */
export const ruleSetRuleContractAbi = ${JSON.stringify(ruleContract.abi, null, 2)} as const;
export const ruleSetRuleContractBytecode: Hex = "${ruleContract.bytecode}";
`;
writeFileSync(OUT, src);
console.log(`wrote ${OUT}: logic ${(logic.bytecode.length - 2) / 2} B, publisher ${(publisher.bytecode.length - 2) / 2} B, rule contract ${(ruleContract.bytecode.length - 2) / 2} B`);
