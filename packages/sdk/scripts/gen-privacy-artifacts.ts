// Generates src/artifacts/privacy.generated.ts (abi + creation code) for the private pool, the stealth vault, the
// Sovereign Account, their Groth16 verifiers and circomlib's Poseidon contract, from `forge build` and the zk fixtures.
//   (cd contracts && forge build) && bun scripts/gen-privacy-artifacts.ts
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("../../../", import.meta.url).pathname;
const OUT = new URL("../src/artifacts/privacy.generated.ts", import.meta.url).pathname;
const art = (n: string) => {
  const j = JSON.parse(readFileSync(`${ROOT}contracts/out/${n}.sol/${n}.json`, "utf8")) as { abi: unknown[]; bytecode: { object: string } };
  return { abi: j.abi, bytecode: j.bytecode.object.startsWith("0x") ? j.bytecode.object : `0x${j.bytecode.object}` };
};
const names = ["PrivatePool", "StealthVault", "SovereignAccount", "WithdrawVerifier", "MembershipVerifier", "StealthVerifier", "EcdsaSigner", "HybridEcdsaSigner", "FalconSigner", "WotsSigner"];
const lc = (n: string) => n[0]!.toLowerCase() + n.slice(1);
let src = `// GENERATED by scripts/gen-privacy-artifacts.ts from contracts/out (solc 0.8.33) and contracts/test/fixtures/poseidon2.hex. Do not edit.
import type { Hex } from "viem";

/** circomlib's Poseidon contract for 2 inputs: poseidon(uint256[2]) returns (uint256). */
export const poseidon2CreationCode: Hex = "${readFileSync(`${ROOT}contracts/test/fixtures/poseidon2.hex`, "utf8").trim()}";
`;
for (const n of names) {
  const a = art(n);
  src += `\nexport const ${lc(n)}Abi = ${JSON.stringify(a.abi)} as const;\nexport const ${lc(n)}Bytecode: Hex = "${a.bytecode}";\n`;
}
writeFileSync(OUT, src);
console.log(`wrote ${OUT}`);
