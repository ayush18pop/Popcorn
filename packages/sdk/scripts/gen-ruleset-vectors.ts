// Writes contracts/test/fixtures/ruleset-vectors.json from test/ruleset.vectors.ts (the Foundry test RuleSetCodec.t.sol reads it).
//   bun packages/sdk/scripts/gen-ruleset-vectors.ts
import { writeFileSync } from "node:fs";
import { encodeRuleSet } from "../src/ruleset/encode.ts";
import { INVALID, VALID } from "../test/ruleset.vectors.ts";

const OUT = new URL("../../../contracts/test/fixtures/ruleset-vectors.json", import.meta.url).pathname;
const doc = {
  note: "generated by packages/sdk/scripts/gen-ruleset-vectors.ts; the SDK encoder and the Solidity builders must both produce `valid`, both validators must refuse `invalid`",
  valid: VALID.map((v) => ({ name: v.name, config: encodeRuleSet(v.spec) })),
  invalid: INVALID.map((v) => ({ name: v.name, config: v.config() })),
};
writeFileSync(OUT, JSON.stringify(doc, null, 2) + "\n");
console.log(`wrote ${OUT}: ${doc.valid.length} valid, ${doc.invalid.length} invalid`);
