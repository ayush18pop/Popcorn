// Generates src/artifacts/sponsor.generated.ts (creation code of the Open Sponsor payer) from contracts/sponsor/out.
//   bash contracts/sponsor/build.sh && bun scripts/gen-sponsor-artifact.ts
import { readFileSync, writeFileSync } from "node:fs";
import { keccak256 } from "viem";

const ROOT = new URL("../../../", import.meta.url).pathname;
const OUT = new URL("../src/artifacts/sponsor.generated.ts", import.meta.url).pathname;
const bin = `0x${readFileSync(`${ROOT}contracts/sponsor/out/OpenSponsor.bin`, "utf8").trim()}` as const;
writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-sponsor-artifact.ts from contracts/sponsor/OpenSponsor.yul (solc 0.8.33, strict assembly). Do not edit.
import type { Hex } from "viem";

/** Creation code; append owner, period, maxFee, defaultLimit (4 x 32 bytes). */
export const openSponsorCreationCode: Hex = "${bin}";
export const OPEN_SPONSOR_CREATION_CODE_HASH: Hex = "${keccak256(bin)}";
`,
);
console.log(`wrote ${OUT}: ${(bin.length - 2) / 2} B`);
