// Self-generated test vectors for the signed-intent predicates (contracts/test/Intent*.t.sol read them).
// Keys are throwaway test constants derived from a label, never funded. Regenerate: bun packages/sdk/scripts/gen-intent-vectors.ts
import { writeFileSync } from "node:fs";
import { keccak256, toHex, type Hex } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import {
  Scheme, attestationDigest, attestedParams, attestedWitness, buildWebAuthnAssertion, domainSeparator, ecdsaParams, hybridEcdsaWotsParams, intentContext, intentDigest, memoryUsageStore,
  multisigParams, multisigWitness, p256Keygen, p256Params, signAttestation, signEcdsaIntent, signP256Intent, webauthnParams, wotsIntentSigner, wotsKeygen, wotsParams,
  type IntentBinding,
} from "../src/intent.ts";

const sk = (label: string): Hex => keccak256(toHex(`popcorn t2 test key: ${label}`));
const CHAIN_ID = 1338;
const RULE_CONTRACT = "0x1111111111111111111111111111111111111111" as const;
const b: IntentBinding = { chainId: CHAIN_ID, ruleContract: RULE_CONTRACT, ruleId: 4, ruleEpoch: 7, triggerData: "0xdeadbeef00112233" };
const digest = intentDigest(b);

const ecdsa = privateKeyToAccount(sk("ecdsa-0"));
const ecdsa1 = privateKeyToAccount(sk("ecdsa-1"));
const ecdsa2 = privateKeyToAccount(sk("ecdsa-2"));
const attestors = [privateKeyToAccount(sk("att-0")), privateKeyToAccount(sk("att-1")), privateKeyToAccount(sk("att-2"))];
const pk = p256Keygen(sk("p256-0"));
const pk2 = p256Keygen(sk("p256-1"));
const wk = p256Keygen(sk("webauthn-0"));
const tree = wotsKeygen(sk("wots-skSeed"), sk("wots-pubSeed"));
const FIRST = 5; // ruleEpoch 7 -> leaf 2
const wsigner = wotsIntentSigner({ tree, firstEpoch: FIRST, binding: { chainId: CHAIN_ID, ruleContract: RULE_CONTRACT, ruleId: 4 }, store: memoryUsageStore(), budget: { maxSteps: 520, maxTries: 2000 } });
const statement = keccak256(toHex("ETH/USD above 5000"));

const out: Record<string, unknown> = {
  note: "self-generated by packages/sdk/scripts/gen-intent-vectors.ts; throwaway test keys",
  chainId: CHAIN_ID, ruleContract: RULE_CONTRACT, ruleId: 4, ruleEpoch: 7, triggerData: b.triggerData,
  context: intentContext(b), digest, domainSeparator: domainSeparator(CHAIN_ID, RULE_CONTRACT),
};
out.ecdsa = { signer: ecdsa.address, params: ecdsaParams(ecdsa.address), witness: await signEcdsaIntent(ecdsa, b), otherSigner: ecdsa1.address, otherWitness: await signEcdsaIntent(ecdsa1, b) };
out.p256 = { params: p256Params(pk), witness: signP256Intent(pk, b), otherParams: p256Params(pk2) };
const wa = buildWebAuthnAssertion(wk, digest, { rpId: "popcorn.example" });
const waNoUv = buildWebAuthnAssertion(wk, digest, { rpId: "popcorn.example", userVerified: false });
const waNoUp = buildWebAuthnAssertion(wk, digest, { rpId: "popcorn.example", userPresent: false, userVerified: false });
const b64 = Buffer.from(digest.slice(2), "hex").toString("base64url");
const waBadJson = buildWebAuthnAssertion(wk, digest, { clientDataJSON: `{"type":"webauthn.get","challenge":"${b64}` }); // cut before the closing quote
const waNoChallenge = buildWebAuthnAssertion(wk, digest, { clientDataJSON: JSON.stringify({ type: "webauthn.get", chall: b64, origin: "https://popcorn.example" }) });
const waWrongChallenge = buildWebAuthnAssertion(wk, digest, { clientDataJSON: JSON.stringify({ type: "webauthn.get", challenge: b64.slice(0, 42) + (b64[42] === "A" ? "B" : "A"), origin: "https://popcorn.example" }) });
const waUnterminated = buildWebAuthnAssertion(wk, digest, { clientDataJSON: `{"type":"webauthn.get","challenge":"${b64}","origin":"x"` }); // no closing brace: not parsed, accepted by design
const waOtherType = buildWebAuthnAssertion(wk, digest, { clientDataJSON: JSON.stringify({ type: "webauthn.create", challenge: b64, origin: "https://popcorn.example" }) });
out.webauthn = {
  params: webauthnParams({ ...wk, rpId: "popcorn.example" }), paramsUV: webauthnParams({ ...wk, rpId: "popcorn.example", requireUV: true }), paramsNoRp: webauthnParams({ ...wk, allowAnyRp: true }),
  paramsOtherRp: webauthnParams({ ...wk, rpId: "other.example" }),
  witness: wa.witness, witnessNoUv: waNoUv.witness, witnessNoUp: waNoUp.witness, witnessBadJson: waBadJson.witness, witnessNoChallenge: waNoChallenge.witness, witnessWrongChallenge: waWrongChallenge.witness, witnessUnterminated: waUnterminated.witness, witnessCreate: waOtherType.witness,
  typeIndex: wa.typeIndex, challengeIndex: wa.challengeIndex, clientDataJSON: wa.clientDataJSON,
};
out.wots = { params: wsigner.params, witness: wsigner.sign(b), root: tree.root, pubSeed: tree.pubSeed, firstEpoch: FIRST, leaf: 7 - FIRST };
out.hybrid = {
  params: hybridEcdsaWotsParams(ecdsa.address, wsigner.key), ecdsaWitness: await signEcdsaIntent(ecdsa, b), wotsWitness: wsigner.sign(b),
};
const msKeys = [
  { scheme: Scheme.ECDSA, key: ecdsaParams(ecdsa.address) },
  { scheme: Scheme.P256, key: p256Params(pk) },
  { scheme: Scheme.WOTS, key: wsigner.params },
];
const msSigs = [
  { index: 0, sig: await signEcdsaIntent(ecdsa, b) },
  { index: 1, sig: signP256Intent(pk, b) },
  { index: 2, sig: wsigner.sign(b) },
];
out.multisig = {
  params: multisigParams(2, msKeys), sigs: msSigs.map((s) => s.sig), witness01: multisigWitness(2, [msSigs[0]!, msSigs[1]!]), witness02: multisigWitness(2, [msSigs[0]!, msSigs[2]!]), witness12: multisigWitness(2, [msSigs[1]!, msSigs[2]!]),
  witness021: multisigWitness(3, msSigs).replace(/^0x03/, "0x02"),
  params3of3: multisigParams(3, msKeys), witness3: multisigWitness(3, msSigs),
};
const attSigs = await Promise.all(attestors.map((a, i) => signAttestation(a, { ...b, statement }).then((sig) => ({ index: i, sig }))));
out.attested = {
  statement, params: attestedParams(statement, 2, attestors.map((a) => a.address)), witness: attestedWitness(2, [attSigs[0]!, attSigs[2]!]), sigs: attSigs.map((s) => s.sig),
  digest: attestationDigest({ ...b, statement }), attestors: attestors.map((a) => a.address),
};
out.ecdsaExtra = { ecdsa2: ecdsa2.address };
writeFileSync(new URL("../../../contracts/test/fixtures/intent-vectors.json", import.meta.url), JSON.stringify(out, null, 2) + "\n");
console.log("wrote contracts/test/fixtures/intent-vectors.json");
